import React, { useEffect, useState } from 'react';
import { 
  AreaChart, 
  Area, 
  XAxis, 
  YAxis, 
  CartesianGrid, 
  Tooltip, 
  ResponsiveContainer, 
  Legend,
  Line
} from 'recharts';
import { 
  TrendingUp, 
  Calendar, 
  AlertTriangle, 
  Clock, 
  Sparkles, 
  Cpu, 
  CheckCircle2, 
  ArrowRight,
  ShieldAlert
} from 'lucide-react';
import { api } from '../api/client';

export const ForecastPage: React.FC = () => {
  const [days, setDays] = useState(7);
  const [startDate, setStartDate] = useState('');
  const [forecast, setForecast] = useState<any>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const fetchForecast = async (hDays: number, sDate?: string) => {
    setLoading(true);
    setError(null);
    try {
      const data = await api.getForecast(hDays, sDate || undefined);
      setForecast(data);
    } catch (err: any) {
      setError(err.message || 'Failed to fetch ML forecast from datathonapi.');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchForecast(days, startDate);
  }, []);

  const handleApply = (e: React.FormEvent) => {
    e.preventDefault();
    fetchForecast(days, startDate);
  };

  const chartData = forecast?.predictions?.map((p: any) => ({
    date: p.date,
    day_name: p.day_name,
    predicted: p.predicted_requests,
    lower: p.confidence_interval?.lower_95,
    upper: p.confidence_interval?.upper_95,
    range: [p.confidence_interval?.lower_95, p.confidence_interval?.upper_95]
  })) || [];

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-8 space-y-8">
      {/* Title & Engine Attribution */}
      <div className="bg-slate-900 border border-slate-800 rounded-3xl p-6 sm:p-8 text-white relative overflow-hidden shadow-xl">
        <div className="max-w-3xl space-y-3">
          <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-teal-500/20 text-teal-300 text-xs font-semibold border border-teal-500/30">
            <Cpu className="w-3.5 h-3.5 text-teal-400" />
            Powered by datathonapi (FastAPI ML Service)
          </div>
          <h1 className="text-2xl sm:text-4xl font-extrabold tracking-tight">
            Campus Room-Request Demand Forecast
          </h1>
          <p className="text-slate-300 text-sm sm:text-base leading-relaxed">
            Multi-step recursive time-series forecasting generated by an independently trained <span className="text-teal-400 font-semibold">RandomForestRegressor</span> model using calendar features and lagged demand observations.
          </p>
        </div>
      </div>

      {/* Synthetic Warning Banner */}
      <div className="bg-amber-500/10 border border-amber-500/30 rounded-2xl p-4 sm:p-5 flex items-start gap-3.5 text-amber-900">
        <AlertTriangle className="w-5 h-5 text-amber-600 shrink-0 mt-0.5" />
        <div className="space-y-1 text-xs">
          <span className="font-bold text-amber-900">Synthetic Model Warning:</span>
          <p className="text-amber-800 leading-relaxed">
            {forecast?.synthetic_data_warning || 'Forecasts reflect statistical patterns in synthetic datathon requests. Not validated against real-world campus physical access badge readers.'}
          </p>
        </div>
      </div>

      {/* Horizon Controls */}
      <div className="bg-white rounded-2xl p-6 border border-slate-200 shadow-xs">
        <form onSubmit={handleApply} className="flex flex-wrap items-end justify-between gap-4">
          <div className="flex flex-wrap items-center gap-4">
            <div>
              <label className="block text-xs font-semibold uppercase tracking-wider text-slate-500 mb-1.5">
                Forecast Horizon
              </label>
              <div className="flex rounded-lg bg-slate-100 p-1 border border-slate-200">
                {[7, 14, 21, 30].map((d) => (
                  <button
                    key={d}
                    type="button"
                    onClick={() => {
                      setDays(d);
                      fetchForecast(d, startDate);
                    }}
                    className={`px-3.5 py-1.5 rounded-md text-xs font-semibold transition-colors ${
                      days === d ? 'bg-teal-600 text-white shadow-xs' : 'text-slate-600 hover:text-slate-900'
                    }`}
                  >
                    {d} Days
                  </button>
                ))}
              </div>
            </div>

            <div>
              <label className="block text-xs font-semibold uppercase tracking-wider text-slate-500 mb-1.5">
                Start Date (Optional)
              </label>
              <input
                type="date"
                value={startDate}
                onChange={(e) => setStartDate(e.target.value)}
                placeholder="YYYY-MM-DD"
                className="px-3 py-1.5 rounded-lg border border-slate-300 text-xs text-slate-800 font-medium focus:ring-2 focus:ring-teal-500"
              />
            </div>
          </div>

          <button
            type="submit"
            disabled={loading}
            className="px-5 py-2 rounded-lg bg-teal-600 hover:bg-teal-700 text-white text-xs font-semibold shadow-xs flex items-center gap-2 transition-colors disabled:opacity-50 cursor-pointer"
          >
            {loading ? (
              <>
                <div className="w-3.5 h-3.5 border-2 border-white border-t-transparent rounded-full animate-spin" />
                <span>Generating Forecast...</span>
              </>
            ) : (
              <>
                <TrendingUp className="w-3.5 h-3.5" />
                <span>Update Forecast</span>
              </>
            )}
          </button>
        </form>
      </div>

      {error && (
        <div className="bg-rose-50 border border-rose-200 text-rose-800 p-4 rounded-xl text-xs">
          {error}
        </div>
      )}

      {/* Main Forecast Chart */}
      {forecast && (
        <div className="bg-white rounded-2xl p-6 border border-slate-200 shadow-xs space-y-4">
          <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-2 border-b border-slate-100 pb-4">
            <div>
              <h3 className="text-base font-bold text-slate-900">
                Daily Forecasted Room Requests ({forecast.start_date} to {forecast.end_date})
              </h3>
              <p className="text-xs text-slate-500 mt-0.5">
                Model: <span className="font-semibold text-slate-700">{forecast.model_name}</span> • Showing point estimates and 95% confidence intervals
              </p>
            </div>
            <div className="flex items-center gap-4 text-xs font-medium">
              <span className="flex items-center gap-1.5 text-teal-700">
                <span className="w-3 h-1 bg-teal-600 rounded-full" />
                Predicted Requests
              </span>
              <span className="flex items-center gap-1.5 text-slate-400">
                <span className="w-3 h-3 bg-teal-100 rounded-sm border border-teal-300" />
                95% Confidence Band
              </span>
            </div>
          </div>

          <div className="h-80 w-full">
            <ResponsiveContainer width="100%" height="100%">
              <AreaChart data={chartData} margin={{ top: 15, right: 15, left: -10, bottom: 20 }}>
                <defs>
                  <linearGradient id="predGrad" x1="0" y1="0" x2="0" y2="1">
                    <stop offset="5%" stopColor="#0d9488" stopOpacity={0.25}/>
                    <stop offset="95%" stopColor="#0d9488" stopOpacity={0.0}/>
                  </linearGradient>
                </defs>
                <CartesianGrid strokeDasharray="3 3" vertical={false} stroke="#f1f5f9" />
                <XAxis dataKey="date" tick={{ fontSize: 11 }} />
                <YAxis tick={{ fontSize: 11 }} />
                <Tooltip
                  contentStyle={{ backgroundColor: '#0f172a', borderRadius: '8px', color: '#fff', fontSize: '12px' }}
                  formatter={(value: any, name: any) => [
                    `${value} requests`,
                    name === 'predicted' ? 'Predicted Demand' : String(name || '')
                  ]}
                />
                <Area type="monotone" dataKey="upper" name="Upper 95% CI" stroke="transparent" fill="#99f6e4" fillOpacity={0.5} />
                <Area type="monotone" dataKey="predicted" name="Predicted Demand" stroke="#0d9488" strokeWidth={3} fill="url(#predGrad)" />
                <Area type="monotone" dataKey="lower" name="Lower 95% CI" stroke="transparent" fill="#ffffff" fillOpacity={1} />
              </AreaChart>
            </ResponsiveContainer>
          </div>
        </div>
      )}

      {/* Daily Breakdown Cards */}
      {forecast && (
        <div className="space-y-4">
          <h3 className="text-sm font-bold text-slate-900 uppercase tracking-wider">
            Day-by-Day Forecast Breakdown
          </h3>

          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
            {forecast.predictions?.map((item: any) => (
              <div
                key={item.date}
                className="bg-white rounded-xl border border-slate-200 p-4 space-y-3 hover:border-teal-500/40 transition-colors shadow-xs"
              >
                <div className="flex items-start justify-between">
                  <div>
                    <span className="text-xs font-bold text-slate-800">{item.day_name}</span>
                    <p className="text-[11px] text-slate-400">{item.date}</p>
                  </div>
                  <span className={`text-[10px] px-2 py-0.5 rounded-full font-semibold ${
                    item.is_weekend ? 'bg-slate-100 text-slate-600' : 'bg-teal-50 text-teal-700 border border-teal-200'
                  }`}>
                    {item.is_weekend ? 'Weekend' : 'Weekday'}
                  </span>
                </div>

                <div>
                  <div className="text-2xl font-black text-slate-900">
                    {item.predicted_requests}
                    <span className="text-xs font-normal text-slate-500 ml-1">requests</span>
                  </div>
                  <p className="text-[11px] text-slate-400 mt-0.5">
                    95% Range: {item.confidence_interval?.lower_95} - {item.confidence_interval?.upper_95}
                  </p>
                </div>

                <div className="pt-2 border-t border-slate-100 space-y-1">
                  <span className="text-[10px] uppercase font-semibold text-slate-400 flex items-center gap-1">
                    <Clock className="w-3 h-3 text-slate-400" />
                    Expected Peak Hours:
                  </span>
                  <div className="flex flex-wrap gap-1 text-[11px]">
                    {item.expected_peak_hours?.map((h: number) => (
                      <span key={h} className="px-1.5 py-0.5 rounded bg-slate-100 text-slate-700 font-mono text-[10px]">
                        {h}:00
                      </span>
                    ))}
                  </div>
                </div>
              </div>
            ))}
          </div>
        </div>
      )}
    </div>
  );
};
